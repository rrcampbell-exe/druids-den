import { describe, expect, it } from 'vitest'
import { render, screen, within } from '@testing-library/react'
import { BrowserRouter } from 'react-router'
import { TheDen } from '../../src/pages/PublicPages'

const renderWithRouter = (component) => render(<BrowserRouter>{component}</BrowserRouter>)

describe('The Den', () => {
  it('uses the interior collection to tell the story of the cabin', () => {
    renderWithRouter(<TheDen />)

    expect(screen.getByAltText('The open-plan main room with its living room, kitchen, and loft')).toHaveAttribute('src', '/assets/images/druids_den_main_room_from_living_area.jpeg')
    expect(screen.getByText('Four guests.')).toBeInTheDocument()
    expect(screen.getByText('One private bedroom and an open loft.')).toBeInTheDocument()
    expect(screen.getByText('One bathroom.')).toBeInTheDocument()
    expect(screen.getByText(/Up to four vehicles, including trailers/)).toBeInTheDocument()
    expect(screen.getByText('The private bedroom features a queen bed, windows with drawable shades, and forest-facing views.')).toBeInTheDocument()
    expect(screen.getByText('Open to the main living area and reachable by stairs, the open loft also has a queen bed.')).toBeInTheDocument()
    expect(screen.queryByText(/air-mattress|limited headroom|headroom beneath the eaves/i)).not.toBeInTheDocument()
    expect(screen.getByAltText('The dining table, kitchen, and loft in the open-plan main room')).toBeInTheDocument()
    expect(screen.getByAltText('The living area viewed from the hallway')).toBeInTheDocument()
    expect(screen.getByAltText('Books on the living-room shelf beneath the vaulted wood ceiling')).toBeInTheDocument()
    expect(screen.getByAltText('The open loft above the main living area, viewed from the stairway')).toBeInTheDocument()
    expect(screen.getByAltText('A view across the open loft toward a forest-facing window')).toBeInTheDocument()
    expect(screen.getByAltText('A fawn figurine resting beside a pinecone')).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Warmth and gathering space.' })).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'The loft, above it all.' })).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Amenities by room.' })).toBeInTheDocument()
    const amenitiesSection = screen.getByRole('heading', { name: 'Amenities by room.' }).closest('section')
    const amenities = within(amenitiesSection)
    expect(amenities.getByRole('heading', { name: 'Kitchen' })).toBeInTheDocument()
    expect(amenities.getByRole('heading', { name: 'Living room' })).toBeInTheDocument()
    expect(amenities.getByText('A selection to enjoy during your stay.')).toBeInTheDocument()
    expect(amenities.getByText('Books')).toBeInTheDocument()
    expect(amenities.getByRole('heading', { name: 'Guest supplies' })).toBeInTheDocument()
    expect(amenities.getByText('Cookware')).toBeInTheDocument()
    expect(amenities.getByText('Cookware is available for guest use.')).toBeInTheDocument()
    expect(amenities.getByText('Laundry')).toBeInTheDocument()
    expect(amenities.getByText('Games and cards to enjoy during your stay.')).toBeInTheDocument()
    expect(amenities.getByText('Games')).toBeInTheDocument()
    expect(amenities.getByText('A selection for movie night.')).toBeInTheDocument()
    expect(amenities.getByText('DVDs')).toBeInTheDocument()
    expect(amenities.getByText('Linens & towels')).toBeInTheDocument()
    expect(amenities.getByText('Laundry is available for guest use.')).toBeInTheDocument()
    expect(amenities.getByText('Bed linens and towels are provided.')).toBeInTheDocument()
    expect(amenities.getByRole('heading', { name: 'Primary bedroom' })).toBeInTheDocument()
    expect(amenities.getByRole('heading', { name: 'Open loft' })).toBeInTheDocument()
    expect(amenities.getByRole('heading', { name: 'Bathroom' })).toBeInTheDocument()
    expect(amenities.getByRole('heading', { name: 'Outside' })).toBeInTheDocument()
    expect(amenities.getByText(/Refrigerator, electric range and oven, microwave, and dishwasher/)).toBeInTheDocument()
    expect(amenities.getByText('Coffee maker, filters, and grounds.')).toBeInTheDocument()
    expect(amenities.getByText(/Shower, sink and vanity, and toilet/)).toBeInTheDocument()
    expect(screen.queryByText(/not waterfront|off the property/i)).not.toBeInTheDocument()
  })
})